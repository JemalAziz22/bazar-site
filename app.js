const root = document.documentElement;
const languageSelect = document.querySelector("#language-select");
const themeToggle = document.querySelector("#theme-toggle");
const themeColor = document.querySelector('meta[name="theme-color"]');

function readPreference(key) {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}

function savePreference(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    // Fallback if storage is disabled
  }
}

function setLanguage(language) {
  const selectedLanguage = translations[language] ? language : "ar";
  const copy = translations[selectedLanguage];
  root.lang = selectedLanguage === "ku" ? "ku-Latn" : selectedLanguage;
  root.dir = selectedLanguage === "ar" ? "rtl" : "ltr";
  document.title = copy.pageTitle;

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.content = copy.metaDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = copy[element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute("alt", value);
  });

  if (languageSelect) languageSelect.value = selectedLanguage;
  savePreference("bazar-language", selectedLanguage);
}

function setTheme(theme) {
  const selectedTheme = theme === "dark" ? "dark" : "light";
  const isDark = selectedTheme === "dark";
  const copy = translations[languageSelect ? languageSelect.value : "ar"] || translations.ar;
  root.dataset.theme = selectedTheme;

  if (themeToggle) {
    themeToggle.setAttribute("aria-pressed", String(isDark));
    themeToggle.setAttribute("aria-label", isDark ? copy.enableLightMode : copy.enableDarkMode);
    const label = themeToggle.querySelector(".theme-label");
    const icon = themeToggle.querySelector(".theme-icon");
    if (label) label.textContent = isDark ? copy.lightMode : copy.darkMode;
    if (icon) icon.textContent = isDark ? "☀" : "☾";
  }

  if (themeColor) {
    themeColor.content = isDark ? "#0b1120" : "#f8fafc";
  }
  savePreference("bazar-theme", selectedTheme);
}

// SCREEN SHOWCASE TAB SWITCHING LOGIC
const screenTabs = document.querySelectorAll(".screen-tab");
const screenPanels = document.querySelectorAll(".screen-panel");

if (screenTabs.length > 0) {
  screenTabs.forEach((tab) => {
    tab.addEventListener("click", () => {
      const targetId = tab.dataset.target;
      screenTabs.forEach((t) => {
        t.classList.remove("active");
        t.setAttribute("aria-selected", "false");
      });
      screenPanels.forEach((p) => p.classList.remove("active"));

      tab.classList.add("active");
      tab.setAttribute("aria-selected", "true");
      const targetPanel = document.getElementById(targetId);
      if (targetPanel) targetPanel.classList.add("active");
    });
  });
}

if (languageSelect) {
  languageSelect.addEventListener("change", (event) => {
    setLanguage(event.target.value);
    setTheme(root.dataset.theme);
  });
}

if (themeToggle) {
  themeToggle.addEventListener("click", () => {
    setTheme(root.dataset.theme === "dark" ? "light" : "dark");
  });
}

const savedLanguage = readPreference("bazar-language");
const savedTheme = readPreference("bazar-theme");
const systemPrefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
setLanguage(savedLanguage || "ar");
setTheme(savedTheme || (systemPrefersDark ? "dark" : "light"));
